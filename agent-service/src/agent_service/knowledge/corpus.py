def diagnosis_rubric_corpus() -> list[KnowledgeEvidence]:
  """
  诊断评分点知识库（运行时使用），从 md 文件加载：``RUBRIC_DIR``（默认 agent-service/knowledge/rubric）。
  改 md 后重启 agent-service 生效，不需要重新 build。

  初始内容就是检索评测 v0.3 的 34 条（60 条人工审核 Golden Query 按这些 id 标注）；检索评测继续用
  ``load_benchmark_corpus("v0.3")`` 这份冻结快照，保证评测数字可复现。
  目录不存在时（例如只装了 Python 包）退回冻结快照并记录警告；目录存在但格式错误则直接报错。
  """
  from agent_service.config import get_settings
  from agent_service.knowledge.rubric_loader import default_rubric_dir, load_rubric_dir

  directory = Path(get_settings().rubric_dir or default_rubric_dir())
  if not directory.is_dir():
    logging.getLogger(__name__).warning("rubric_dir_missing path=%s, falling back to frozen v0.3 corpus", directory)
    return _benchmark_corpus_v03()
  return load_rubric_dir(directory)


def load_benchmark_corpus(version: str = "v0.3") -> list[KnowledgeEvidence]:
  """Versioned corpus used by the retrieval benchmark; the same content is the runtime rubric (diagnosis_rubric_corpus)."""
  if version != "v0.3":
    raise ValueError(f"Unsupported benchmark corpus version: {version}")
  return _benchmark_corpus_v03()


